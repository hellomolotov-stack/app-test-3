const assert = require('node:assert/strict');
const { routeDates, addRouteDate, grantSeenAt } = require('../lib/route-grants');
const { planRouteHistory } = require('../lib/route-history');
const old = { userId:'1', name:'a', date:'2025-05-25', issuedAt:1 };
const twice = addRouteDate(old, {userId:'1',name:'a'}, '2026-11-08', 10, 'auto');
assert.deepEqual(routeDates(twice), ['2025-05-25','2026-11-08']);
assert.equal(twice.count, 2);
assert.deepEqual(addRouteDate(twice, {userId:'1',name:'a'}, '2026-11-08', 20, 'auto'), twice);
assert.equal(grantSeenAt(twice, 9), null);
assert.equal(grantSeenAt(twice, 10), 10);
assert.equal(grantSeenAt({...twice, notificationAt:0}, undefined), 10);
const data = {hikes:{'2026-11-08':{title:'route'}},hikeVisitsBefore:{'2025-05-25':{title:'route',people:{'1':'a','2':'b'}}},hikeParticipants:{'2026-11-08':{'1':{name:'a'},'3':{name:'c'},'4':{name:'absent'},'7845375334':{name:'support'}}},noShows:{'2026-11-08':{'4':true}},clubAchievements:{r:{id:'r',title:'route',kind:'special',medal:{imageUrl:'/a.png'},publicationStatus:'published',grants:{'1':old}}}};
const plan = planRouteHistory(data, title=>title, {through:'2026-11-08',notifyDate:'2026-11-08',now:10});
assert.equal(plan.hikes.length, 2);
assert.equal(plan.notify.length, 2);
const rec = plan.changes[0].record;
assert.equal(rec.kind, 'route');
assert.equal(rec.grants['1'].count, 2);
assert.equal(rec.grants['2'].notificationAt, 0);
assert.equal(grantSeenAt(rec.grants['2'], undefined), rec.grants['2'].issuedAt);
assert.equal(grantSeenAt(rec.grants['1'], 9), null);
assert.ok(!rec.grants['4'] && !rec.grants['7845375334']);
data.clubAchievements.r = rec;
assert.equal(planRouteHistory(data,title=>title,{through:'2026-11-08',notifyDate:'2026-11-08',now:20}).changes.length,0);
console.log('Route grants: repeated dates, idempotency, silent history, fresh popup version, no-shows and support exclusions: PASS');
