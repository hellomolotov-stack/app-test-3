const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('appscript-analytics.gs', 'utf8');
const ctx = { console, Date, Number, JSON };
vm.createContext(ctx);
vm.runInContext(source, ctx);
const base = Date.parse('2026-10-22T10:00:00Z');
const day = '2026-10-25';
const event = (uid, name, delta, member = false) => ({ id: `${uid}-${name}-${delta}`, uid, event: name, at: base + delta, date: day, member });
const flow = uid => [event(uid, 'app_open', 0), event(uid, 'hike_view', 1000), event(uid, 'booking_intent', 2000), event(uid, 'booking_success', 5000)];
const payment = (uid, type = 'ticket', paid = true) => ({ user_id: uid, hike_date: day, card_type: type, ts: (base + 3000) / 1000, completed: paid, paid_at: paid ? (base + 5000) / 1000 : undefined });
const aggregate = (events, payments = {}, regs = {}, from = base, to = base + 10000, now = base + 20000) => ctx.caAggregate_(events, payments, regs, day, from, to, now, base);
let result = aggregate([...flow('1'), ...flow('1')], { a: payment('1') }, { 1: { [day]: true } });
assert.deepEqual(Array.from(result.guest), [1, 1, 1, 1, 1, 1]);
assert.equal(result.paid, 1);
assert.equal(result.mismatch, 0);
result = aggregate([event('1', 'hike_view', 0), event('1', 'app_open', 1000), event('1', 'booking_intent', 2000)]);
assert.deepEqual(Array.from(result.guest), [1, 0, 0, 0, 0, 0], 'never invent skipped/out-of-order stages');
result = aggregate(flow('2'), { b: payment('2', 'permanent') });
assert.deepEqual(Array.from(result.guest), [1, 1, 1, 0, 0, 0]);
assert.equal(result.alternative, 1, 'card purchase is not ticket loss');
result = aggregate(flow('3').map(e => ({ ...e, member: true })));
assert.deepEqual(Array.from(result.member), [1, 1, 1, 1]);
result = aggregate([...flow('163665735'), ...flow('7845375334')], { a: payment('163665735') }, { 163665735: { [day]: true } });
assert.equal(result.cohorts, 0); assert.equal(result.active, 0); assert.equal(result.paid, 0);
result = aggregate([...flow('1').slice(0, 3), event('1', 'booking_success', 86405000)], {
  a: { ...payment('1'), paid_at: (base + 86405000) / 1000 }
}, {}, base, base + 10000, base + 86500000);
assert.equal(result.guest[5], 1, 'cohort includes verified next-day payment');
assert.equal(result.paid, 0, 'operational payments have their own period');
result = aggregate(flow('1'), { a: payment('1') }, {});
assert.equal(result.guest[5], 1, 'historic confirmed registration survives later cancellation');
assert.equal(result.active, 0); assert.equal(result.mismatch, 1);
result = aggregate(flow('1'), { a: payment('1', 'ticket', false) });
assert.deepEqual(Array.from(result.guest), [1, 1, 1, 1, 0, 0]);
result = aggregate(flow('1').map(e => ({ ...e, at: e.at - 86400000 })));
assert.equal(result.cohorts, 0, 'no synthetic historical funnel');
ctx.UrlFetchApp = { fetch: () => ({ getResponseCode: () => 403, getContentText: () => '{}' }) };
ctx.FIREBASE_URL = 'https://example.invalid/'; ctx.FIREBASE_SECRET = 'test';
assert.throws(() => ctx.caRead_('pending_payments'), /недоступен/);
ctx._adminOut = x => x;
ctx.verifyTelegramInitData_ = () => null;
assert.equal(ctx.handleClubAnalytics_({}).status, 'error');
ctx.verifyTelegramInitData_ = () => ({ id: 163665735 });
assert.equal(ctx.handleClubAnalytics_({ init_data: `auth_date=${Math.floor(Date.now() / 1000)}` }).excluded, true);
const properties = {};
ctx.PropertiesService = { getScriptProperties: () => ({ getProperty: k => properties[k], setProperty: (k, v) => { properties[k] = v; }, deleteProperty: k => { delete properties[k]; } }) };
ctx.LockService = { getScriptLock: () => ({ waitLock() {}, releaseLock() {} }) };
ctx.Utilities = { formatDate: () => '2026-10-22' };
ctx.getAdminChatId = () => '163665735';
ctx.getBotToken = () => 'test';
ctx.Logger = { log() {} };
ctx.clubAnalyticsReport_ = () => ({ guest: [0, 0, 0, 0, 0, 0], guestLabels: [], member: [0, 0, 0, 0], title: 'тест', date: day, alternative: 0, insights: [], captureStart: base, asOf: base });
ctx.caChart_ = () => 'fake-png';
let sent = 0;
ctx.UrlFetchApp.fetch = () => { sent++; return { getContentText: () => JSON.stringify({ ok: true, result: { message_id: 12 } }) }; };
ctx.sendClubAnalyticsDaily(); ctx.sendClubAnalyticsDaily();
assert.equal(sent, 1, 'daily delivery idempotent');
delete properties.CLUB_ANALYTICS_SENT;
ctx.UrlFetchApp.fetch = () => { sent++; throw new Error('timeout'); };
assert.throws(() => ctx.sendClubAnalyticsDaily(), /timeout/);
assert.throws(() => ctx.sendClubAnalyticsDaily(), /уже начата/);
assert.equal(sent, 2, 'ambiguous send not blindly retried');
